-- ============================================================
-- 给自建 mock 的持仓补"现货开仓均价"。
--
-- 背景：之前 mock 只记了永续空头的开仓均价，现货腿平仓时的已实现盈亏没地方算，
-- 导致 trade_fill 里现货腿的 exec_pnl 全是空、盈亏无法完整归因。
-- 加上现货均价后，现货平仓也能算出已实现盈亏并落库。
-- ============================================================
ALTER TABLE mock_position
    ADD COLUMN spot_avg_price DECIMAL(38,18) NULL COMMENT '现货多头开仓均价' AFTER spot_qty;
