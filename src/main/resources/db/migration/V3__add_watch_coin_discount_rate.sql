-- ============================================================
-- 给监控篮子补上"保证金折扣率"字段。
--
-- 为什么需要：折扣率决定现货能抵多少保证金。
-- 实测（docs/phase-2-strategy-design.md 7.1）：折扣率 0.1 的币涨 9% 就可能强平，
-- 0.8 的币要涨约 3.6 倍，所以折扣率是币种准入的硬指标。
-- ============================================================
ALTER TABLE watch_coin
    ADD COLUMN discount_rate DECIMAL(10,6) NULL COMMENT '保证金折扣率（0~1，越大越安全）' AFTER futures_category;
